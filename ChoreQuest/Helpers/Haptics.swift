import UIKit

/// Tiny wrapper around UIKit's feedback generators so logging a chore feels
/// physical. Called imperatively from button actions on the main thread.
enum Haptics {
    static func success() {
        UINotificationFeedbackGenerator().notificationOccurred(.success)
    }

    static func tap() {
        UIImpactFeedbackGenerator(style: .light).impactOccurred()
    }

    static func selection() {
        UISelectionFeedbackGenerator().selectionChanged()
    }
}
